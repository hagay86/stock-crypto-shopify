def get_stock_universe():
    """Return the full 1000 stock universe as a list of dicts."""
    seen = set()
    universe = []
    for ticker, name, sector, tier in STOCK_UNIVERSE:
        if ticker not in seen:
            seen.add(ticker)
            universe.append({
                "ticker": ticker,
                "name": name,
                "sector": sector,
                "tier": tier,
            })
    return universe


def get_tickers():
    """Return just the ticker symbols."""
    seen = set()
    tickers = []
    for ticker, _, _, _ in STOCK_UNIVERSE:
        if ticker not in seen:
            seen.add(ticker)
            tickers.append(ticker)
    return tickers


def get_sector_breakdown():
    """Return count of stocks per sector."""
    from collections import Counter
    universe = get_stock_universe()
    return Counter(s["sector"] for s in universe)


def get_tier_breakdown():
    """Return count of stocks per tier."""
    from collections import Counter
    universe = get_stock_universe()
    return Counter(s["tier"] for s in universe)


